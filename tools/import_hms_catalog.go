// Import the MIT-licensed bambulan HMS catalog using Go's syntax parser.
// Usage: go run tools/import_hms_catalog.go -source /path/to/bambulan/internal/hms/codes_generated.go
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	source := flag.String("source", "", "bambulan codes_generated.go path")
	output := flag.String("output", "lib/bambu_hms_catalog.g.dart", "generated Dart catalog")
	flag.Parse()
	file, err := parser.ParseFile(token.NewFileSet(), *source, nil, 0)
	check(err)
	entries := map[string]string{}
	ast.Inspect(file, func(node ast.Node) bool {
		value, ok := node.(*ast.ValueSpec)
		if !ok || len(value.Names) != 1 || value.Names[0].Name != "AllCodes" {
			return true
		}
		list := value.Values[0].(*ast.CompositeLit)
		for _, item := range list.Elts {
			pair := item.(*ast.CompositeLit)
			code, err := strconv.ParseUint(pair.Elts[0].(*ast.BasicLit).Value, 0, 64)
			check(err)
			text, err := strconv.Unquote(pair.Elts[1].(*ast.BasicLit).Value)
			check(err)
			if strings.TrimSpace(text) != "" {
				entries[fmt.Sprintf("%016X", code)] = text
			}
		}
		return false
	})
	if len(entries) == 0 {
		panic("No HMS descriptions found")
	}
	license, err := os.ReadFile(strings.TrimSuffix(*source, "internal/hms/codes_generated.go") + "LICENSE")
	check(err)
	var result strings.Builder
	result.WriteString("// Generated by tools/import_hms_catalog.go; do not edit.\n")
	result.WriteString("// Source: github.com/gonzalop/bambulan/internal/hms (MIT).\n//\n")
	for _, line := range strings.Split(strings.TrimSpace(string(license)), "\n") {
		fmt.Fprintf(&result, "// %s\n", line)
	}
	quotedLicense, err := json.Marshal(strings.TrimSpace(string(license)))
	check(err)
	fmt.Fprintf(&result, "\nconst bambuHmsCatalogLicense = %s;\n", string(quotedLicense))
	result.WriteString("\nconst bambuHmsDescriptions = <String, String>{\n")
	keys := make([]string, 0, len(entries))
	for key := range entries {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		quoted, err := json.Marshal(entries[key])
		check(err)
		fmt.Fprintf(&result, "  '%s': %s,\n", key, strings.ReplaceAll(string(quoted), "$", "\\$"))
	}
	result.WriteString("};\n")
	check(os.WriteFile(*output, []byte(result.String()), 0644))
	fmt.Printf("Imported %d HMS descriptions into %s\n", len(entries), *output)
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
